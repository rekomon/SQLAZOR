    public List<GeneratedFile> GenerateDocumentation(
    DatabaseSchema schema,
    IEnumerable<string> selectedTableKeys,
    List<StoredProcedureDetail> proceduresIncluded,
    List<GeneratedFile> allGeneratedFiles,
    string applicationName,
    string rootNamespace,
    string dbContextName,
    bool includeCrudServices,
    bool includeApiEndpoints,
    bool includeHttpClientServices,
    bool includeBlazorPages,
    PageStyle pageStyle,
    bool useCleanArchitecture)
    {
        var selected = selectedTableKeys.ToHashSet(StringComparer.OrdinalIgnoreCase);
        var tables = schema.Tables.Where(t => selected.Contains(t.FullyQualifiedName)).OrderBy(t => t.TableName).ToList();
        var relevantFks = schema.ForeignKeys
            .Where(fk => selected.Contains($"{fk.ParentSchema}.{fk.ParentTable}") && selected.Contains($"{fk.ReferencedSchema}.{fk.ReferencedTable}"))
            .ToList();

        var html = BuildDocumentationHtml(
            schema, tables, relevantFks, proceduresIncluded, allGeneratedFiles,
            applicationName, rootNamespace, dbContextName, includeCrudServices, includeApiEndpoints,
            includeHttpClientServices, includeBlazorPages, pageStyle, useCleanArchitecture);

        return [new GeneratedFile { RelativePath = "docs/index.html", Content = html }];
    }


    private static string BuildDocumentationHtml(
    DatabaseSchema schema,
    List<TableInfo> tables,
    List<ForeignKeyInfo> relevantFks,
    List<StoredProcedureDetail> procedures,
    List<GeneratedFile> allFiles,
    string applicationName,
    string rootNamespace,
    string dbContextName,
    bool includeCrudServices,
    bool includeApiEndpoints,
    bool includeHttpClientServices,
    bool includeBlazorPages,
    PageStyle pageStyle,
    bool useCleanArchitecture)
    {
        var hasProjectFiles = allFiles.Any(f => f.RelativePath.EndsWith(".csproj") || f.RelativePath.EndsWith(".sln"));
        var pageStyleName = pageStyle switch { PageStyle.MudBlazor => "MudBlazor", PageStyle.Tabler => "Tabler", _ => "Plain HTML" };

        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html>");
        sb.AppendLine("<html lang=\"en\">");
        sb.AppendLine("<head>");
        sb.AppendLine("<meta charset=\"UTF-8\" />");
        sb.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\" />");
        sb.AppendLine($"<title>{Constant.HtmlEncode(applicationName)} \u2014 Documentation</title>");
        sb.AppendLine("<style>");
        sb.AppendLine(DocumentationCss);
        sb.AppendLine("</style>");
        sb.AppendLine("</head>");
        sb.AppendLine("<body>");
        sb.AppendLine("<div class=\"doc-shell\">");

        // ---- sidebar ----
        sb.AppendLine("  <nav class=\"doc-sidebar\">");
        sb.AppendLine($"    <div class=\"doc-brand\">{Constant.HtmlEncode(applicationName)}</div>");
        sb.AppendLine($"    <div class=\"doc-meta\">Generated by SchemaForge<br/>{DateTime.Now:yyyy-MM-dd}</div>");
        sb.AppendLine("    <a href=\"#overview\">Overview</a>");
        sb.AppendLine("    <a href=\"#architecture\">Architecture</a>");
        sb.AppendLine($"    <a href=\"#entities\">Entities ({tables.Count})</a>");
        if (relevantFks.Count > 0) sb.AppendLine("    <a href=\"#relationships\">Relationships</a>");
        if (includeApiEndpoints) sb.AppendLine("    <a href=\"#endpoints\">API Endpoints</a>");
        if (procedures.Count > 0) sb.AppendLine("    <a href=\"#procedures\">Stored Procedures</a>");
        sb.AppendLine("    <a href=\"#structure\">Project Structure</a>");
        sb.AppendLine("    <a href=\"#getting-started\">Getting Started</a>");
        sb.AppendLine("  </nav>");

        sb.AppendLine("  <main class=\"doc-content\">");

        AppendOverviewSection(sb, schema, tables, procedures, applicationName, includeCrudServices,
            includeApiEndpoints, includeHttpClientServices, includeBlazorPages, pageStyleName, useCleanArchitecture);

        AppendArchitectureSection(sb, applicationName, rootNamespace, dbContextName, useCleanArchitecture,
            includeCrudServices, includeApiEndpoints, includeHttpClientServices, includeBlazorPages, pageStyleName);

        AppendEntitiesSection(sb, tables, relevantFks);

        if (relevantFks.Count > 0)
        {
            AppendRelationshipsSection(sb, relevantFks);
        }

        if (includeApiEndpoints)
        {
            AppendEndpointsSection(sb, tables);
        }

        if (procedures.Count > 0)
        {
            AppendProceduresSection(sb, procedures);
        }

        AppendStructureSection(sb, allFiles, applicationName, useCleanArchitecture);

        AppendGettingStartedSection(sb, applicationName, useCleanArchitecture, hasProjectFiles, includeCrudServices);

        sb.AppendLine("  </main>");
        sb.AppendLine("</div>");
        sb.AppendLine("</body>");
        sb.AppendLine("</html>");

        return sb.ToString();
    }

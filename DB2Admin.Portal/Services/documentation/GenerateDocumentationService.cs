    private static void AppendEntitiesSection(StringBuilder sb, List<TableInfo> tables, List<ForeignKeyInfo> relevantFks)
    {
        sb.AppendLine("    <section id=\"entities\">");
        sb.AppendLine("      <h2>Entities</h2>");

        foreach (var table in tables)
        {
            var outgoingCount = relevantFks.Count(fk => fk.ParentSchema == table.Schema && fk.ParentTable == table.TableName);
            var incomingCount = relevantFks.Count(fk => fk.ReferencedSchema == table.Schema && fk.ReferencedTable == table.TableName);

            sb.AppendLine("      <div class=\"entity-card\">");
            sb.AppendLine($"        <h3>{Constant.HtmlEncode(table.ClassName)} <span class=\"entity-source\">{Constant.HtmlEncode(table.Schema)}.{Constant.HtmlEncode(table.TableName)}</span></h3>");
            sb.AppendLine("        <table class=\"doc-table\">");
            sb.AppendLine("          <thead><tr><th>Column</th><th>Property</th><th>Type</th><th>Nullable</th><th></th></tr></thead>");
            sb.AppendLine("          <tbody>");
            foreach (var col in table.Columns.OrderBy(c => c.OrdinalPosition))
            {
                var badges = new List<string>();
                if (col.IsPrimaryKey) badges.Add("<span class=\"tag tag-pk\">PK</span>");
                if (col.IsIdentity) badges.Add("<span class=\"tag\">identity</span>");
                if (col.IsComputed) badges.Add("<span class=\"tag\">computed</span>");
                var fk = relevantFks.FirstOrDefault(f => f.ParentSchema == table.Schema && f.ParentTable == table.TableName && f.ParentColumn == col.ColumnName);
                if (fk is not null) badges.Add($"<span class=\"tag tag-fk\">FK \u2192 {Constant.HtmlEncode(fk.ReferencedTable)}</span>");

                sb.AppendLine("            <tr>");
                sb.AppendLine($"              <td><code>{Constant.HtmlEncode(col.ColumnName)}</code></td>");
                sb.AppendLine($"              <td>{Constant.HtmlEncode(col.PropertyName)}</td>");
                sb.AppendLine($"              <td><code>{Constant.HtmlEncode(col.SqlDataType)}</code></td>");
                sb.AppendLine($"              <td>{(col.IsNullable ? "yes" : "no")}</td>");
                sb.AppendLine($"              <td>{string.Join(" ", badges)}</td>");
                sb.AppendLine("            </tr>");
            }
            sb.AppendLine("          </tbody>");
            sb.AppendLine("        </table>");
            if (outgoingCount > 0 || incomingCount > 0)
            {
                sb.AppendLine($"        <p class=\"entity-rel-summary\">{outgoingCount} outgoing relationship(s), {incomingCount} incoming.</p>");
            }
            sb.AppendLine("      </div>");
        }

        sb.AppendLine("    </section>");
    }



    private static string BuildFileTreeText(IEnumerable<string> relativePaths)
    {
        var root = new SortedDictionary<string, object>(StringComparer.OrdinalIgnoreCase);

        foreach (var path in relativePaths)
        {
            var parts = path.Split('/', StringSplitOptions.RemoveEmptyEntries);
            var node = root;
            for (var i = 0; i < parts.Length; i++)
            {
                var isFile = i == parts.Length - 1;
                if (isFile)
                {
                    node[parts[i]] = true; // leaf marker
                }
                else
                {
                    if (!node.TryGetValue(parts[i], out var next) || next is not SortedDictionary<string, object> nextDict)
                    {
                        nextDict = new SortedDictionary<string, object>(StringComparer.OrdinalIgnoreCase);
                        node[parts[i]] = nextDict;
                    }
                    node = (SortedDictionary<string, object>)node[parts[i]];
                }
            }
        }

        var sb = new StringBuilder();
        RenderTreeLevel(sb, root, 0);
        return sb.ToString();

        static void RenderTreeLevel(StringBuilder sb, SortedDictionary<string, object> level, int depth)
        {
            var indent = new string(' ', depth * 2);
            foreach (var (name, value) in level)
            {
                if (value is SortedDictionary<string, object> childDict)
                {
                    sb.AppendLine($"{indent}{name}/");
                    RenderTreeLevel(sb, childDict, depth + 1);
                }
                else
                {
                    sb.AppendLine($"{indent}{name}");
                }
            }
        }
    }


    private static void AppendEndpointsSection(StringBuilder sb, List<TableInfo> tables)
    {
        sb.AppendLine("    <section id=\"endpoints\">");
        sb.AppendLine("      <h2>API Endpoints</h2>");

        foreach (var table in tables.Where(t => t.PrimaryKeyColumns.Count > 0 && !t.IsView))
        {
            var pluralRoute = NamingHelper.Pluralize(table.ClassName).ToLowerInvariant();
            var routeTemplate = Constant.BuildPkPathSegment(table);

            sb.AppendLine($"      <h4>{Constant.HtmlEncode(table.ClassName)}</h4>");
            sb.AppendLine("      <table class=\"doc-table endpoint-table\">");
            sb.AppendLine("        <tbody>");
            AppendEndpointRow(sb, "GET", $"/api/{pluralRoute}", "Get all");
            AppendEndpointRow(sb, "GET", $"/api/{pluralRoute}/{routeTemplate}", "Get by key");
            AppendEndpointRow(sb, "POST", $"/api/{pluralRoute}", "Create");
            AppendEndpointRow(sb, "PUT", $"/api/{pluralRoute}/{routeTemplate}", "Update");
            AppendEndpointRow(sb, "DELETE", $"/api/{pluralRoute}/{routeTemplate}", "Delete");
            sb.AppendLine("        </tbody>");
            sb.AppendLine("      </table>");
        }

        sb.AppendLine("    </section>");
    }
    

